# 4. MeloTTS 訓練標註檔的設定
SPEAKER_NAME = "Guga" # 給這個聲音取個名字
LANGUAGE = "ZH"              # 語言代碼 (日文 JP, 中文 ZH)
# ==================================================

async def main():
    print("🚀 啟動 Fish Audio 自動資料產生器 (非同步版)...")
    
    # 初始化客戶端，直接傳入 API Key
    client = AsyncFishAudio(api_key=API_KEY)

    # 自動建立存放音檔的資料夾
    os.makedirs("data/guga/wavs", exist_ok=True)

    # 打開 metadata.list 準備寫入
    with open("data/guga/metadata.list", "w", encoding="utf-8") as meta_file:

        # 開始迴圈跑每一句話
        for i, text in enumerate(SENTENCES, start=1):
            file_name = f"{i:03d}.wav"           # 自動補零，例如 001.wav
            relative_path = f"data/guga/wavs/{file_name}"  # 寫入 list 檔用的相對路徑
            print(f"⏳ 正在生成 ({i}/{len(SENTENCES)}): {text}")

            try:
                # 呼叫 API 轉換語音
                audio_bytes = await client.tts.convert(
                    text=text,
                    config=TTSConfig(
                        reference_id=VOICE_ID,
                        format="wav",
                        latency="balanced"
                    )
                )

                # 將回傳的音訊存成 .wav 檔
                with open(relative_path, "wb") as f:
                    f.write(audio_bytes)

                # 組合出 MeloTTS 需要的格式: wavs/001.wav|MyAssistant|JP|こんにちは...
                meta_line = f"{relative_path}|{SPEAKER_NAME}|{LANGUAGE}|{text}\n"
                meta_file.write(meta_line)

                # ⚠️ 關鍵保護機制：暫停 1.5 秒，避免請求過快被伺服器阻擋 (Rate Limit)
                #time.sleep(2)

            except Exception as e:
                print(f"❌ 生成第 {i} 句時發生錯誤: {e}")

    print("\n🎉 全部生成完畢！請檢查目錄下的 'wavs' 資料夾與 'metadata.list' 檔案。")

if __name__ == "__main__":
    asyncio.run(main())